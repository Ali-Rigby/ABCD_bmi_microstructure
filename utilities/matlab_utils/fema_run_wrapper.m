function est_file = fema_run_wrapper(fstem_imaging, fname_design, dirname_out, dirname_imaging, datatype, transform_y, outputType)
%FEMA_RUN_WRAPPER Call FEMA 4.x wrapper with pipeline outPrefix naming.
outPrefix = sprintf('FEMA_wrapper_output_%s_%s', datatype, fstem_imaging);
FEMA_wrapper( ...
    'fstem_imaging', fstem_imaging, ...
    'fname_design', fname_design, ...
    'dirname_out', dirname_out, ...
    'dirname_imaging', dirname_imaging, ...
    'datatype', datatype, ...
    'transformY', transform_y, ...
    'outputType', outputType, ...
    'outPrefix', outPrefix);
est_file = fema_results_path(dirname_out, datatype, fstem_imaging);
end
